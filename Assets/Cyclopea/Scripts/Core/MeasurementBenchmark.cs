using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;

namespace Cyclopea.Core
{
    /// <summary>
    /// A known-answer benchmark for the Depth Score. Thousands of simulated players, each with a true
    /// threshold we set, play the Spot rung through the game's own code (SkillLadder, TrialGate,
    /// Verdict). We then count how often the game is right, wrong, or says it isn't sure, for each
    /// kind of player, including the failures that matter most:
    ///   telling someone with depth vision that they have none,
    ///   giving a number to someone who has no depth from two eyes,
    ///   blaming a broken two-eye view on the player's eyes.
    /// The "true answer" is the disparity each player gets right 79.4 % of the time, the point a
    /// 3-down/1-up staircase is built to find (Levitt 1971).
    /// </summary>
    public static class MeasurementBenchmark
    {
        /// <summary>Lapse rate of an attentive player; above it, lapses are distraction, not eyesight.</summary>
        public const double AttentiveLapse = 0.06;

        public enum Expect { Score, Floor, NoDepth, Uncertain, ScoreOrNoDepth }

        public sealed class Group
        {
            public string Name, Who;
            public Expect Expect;
            public int N;
            public double MinThr, MaxThr, MinSlope = 0.1, MaxSlope = 0.2, MinLapse = 0.02, MaxLapse = 0.06;
            public double DirtyChance;   // fraction of trials a critical health fault touches
            public bool GuessOnly;       // no depth from two eyes: every answer is a guess
            public bool GateOn = true;   // false = the counterfactual game without the health check
        }

        public sealed class Row
        {
            public Group G;
            public int Measured, AtFloor, NoDepth, Uncertain, Right, Wrong;
            public int Within126, Within158, Covered, Flattering;
            public readonly List<double> AbsErrPct = new List<double>();
            public readonly List<int> Trials = new List<int>();
            public double Pct(int k) => 100.0 * k / Math.Max(1, G.N);
        }

        public sealed class Report
        {
            public readonly List<Row> Rows = new List<Row>();
            public double Floor;
            public int Seed;

            public Row this[string name] => Rows.Find(r => r.G.Name == name);

            /// <summary>People who can see depth told they cannot (any group whose players have depth).</summary>
            public (int bad, int n) FalseNoDepth()
            {
                int bad = 0, n = 0;
                foreach (var r in Rows)
                    if (!r.G.GuessOnly && r.G.GateOn && r.G.Expect != Expect.ScoreOrNoDepth) { bad += r.NoDepth; n += r.G.N; }
                return (bad, n);
            }

            /// <summary>Players with no two-eye depth handed a number anyway.</summary>
            public (int bad, int n) FakeNumbers()
            {
                int bad = 0, n = 0;
                foreach (var r in Rows)
                    if (r.G.GuessOnly && r.G.GateOn) { bad += r.Measured + r.AtFloor; n += r.G.N; }
                return (bad, n);
            }

            public string Markdown()
            {
                var ci = CultureInfo.InvariantCulture;
                var sb = new StringBuilder();
                sb.Append("# Depth Score benchmark (known answers)\n\n");
                sb.Append("Generated by `MeasurementBenchmark` (EditMode test `BenchmarkTests`), seed ").Append(Seed)
                  .Append(", display floor ").Append(Floor.ToString("0", ci)).Append("″ (Quest 3). Each simulated player has a true threshold we set; ")
                  .Append("they play the Spot rung through the game's own `SkillLadder`, `TrialGate` and `Verdict` code. ")
                  .Append("The true answer is the disparity a player gets right 79.4 % of the time.\n\n");

                var fnd = FalseNoDepth(); var fake = FakeNumbers();
                var broken = this["Broken two-eye view"]; var brokenOff = this["Broken view, no health check"];
                var steady = this["Steady players"];
                sb.Append("## The errors that matter most\n\n| Error | Rate |\n|---|---|\n");
                sb.Append("| Told \"no depth from two eyes\" when they have it | ").Append(Rate(fnd.bad, fnd.n)).Append(" |\n");
                sb.Append("| Given a number with no depth from two eyes | ").Append(Rate(fake.bad, fake.n)).Append(" |\n");
                if (broken != null)
                    sb.Append("| Broken two-eye view blamed on the player's eyes | ").Append(Rate(broken.NoDepth + broken.Measured + broken.AtFloor, broken.G.N)).Append(" |\n");
                if (brokenOff != null)
                    sb.Append("| ... the same, if the health check were switched off | ").Append(Rate(brokenOff.NoDepth + brokenOff.Measured + brokenOff.AtFloor, brokenOff.G.N)).Append(" |\n");
                int flat = 0, scored = 0;
                foreach (var r in Rows) if (!r.G.GuessOnly && r.G.GateOn) { flat += r.Flattering; scored += r.Measured; }
                sb.Append("| A score finer than the player's eyes really are (by more than ×1.58) | ").Append(Rate(flat, scored)).Append(" |\n");
                if (steady != null)
                {
                    sb.Append("\n## Accuracy for steady players\n\n");
                    int m = steady.Measured;
                    sb.Append("- Scored: ").Append(steady.Pct(steady.Measured + steady.AtFloor).ToString("0.0", ci)).Append(" %; ")
                      .Append("said \"not sure\": ").Append(steady.Pct(steady.Uncertain).ToString("0.0", ci)).Append(" %.\n");
                    sb.Append("- Of the scores: within ×1.26 of the true answer ").Append(P(steady.Within126, m)).Append(", within ×1.58 ").Append(P(steady.Within158, m))
                      .Append("; median error ").Append(Median(steady.AbsErrPct).ToString("0", ci)).Append(" %.\n");
                    sb.Append("- The ± range shown with each score held the true answer ").Append(P(steady.Covered, m)).Append(" of the time.\n");
                    sb.Append("- Median ").Append(MedianInt(steady.Trials)).Append(" rounds to a score.\n");
                }

                sb.Append("\n## Every group\n\n| Group | Players | n | Score | ≤ floor | No depth | Not sure | Right | Wrong | Within ×1.58 | Median rounds |\n|---|---|---|---|---|---|---|---|---|---|---|\n");
                foreach (var r in Rows)
                {
                    sb.Append("| ").Append(r.G.Name).Append(" | ").Append(r.G.Who).Append(" | ").Append(r.G.N)
                      .Append(" | ").Append(r.Pct(r.Measured).ToString("0.0", ci))
                      .Append(" | ").Append(r.Pct(r.AtFloor).ToString("0.0", ci))
                      .Append(" | ").Append(r.Pct(r.NoDepth).ToString("0.0", ci))
                      .Append(" | ").Append(r.Pct(r.Uncertain).ToString("0.0", ci))
                      .Append(" | ").Append(r.Pct(r.Right).ToString("0.0", ci))
                      .Append(" | ").Append(r.Pct(r.Wrong).ToString("0.0", ci))
                      .Append(" | ").Append(r.Measured > 0 ? P(r.Within158, r.Measured) : "—")
                      .Append(" | ").Append(MedianInt(r.Trials)).Append(" |\n");
                }
                sb.Append("\nAll numbers are percentages of the group. \"Right\" means the outcome the group should get: a score within ×1.58 for players with depth, ")
                  .Append("\"≤ floor\" for players finer than the display, \"no depth\" or \"not sure\" for players with none, \"not sure\" when the view is broken. ")
                  .Append("\"Not sure\" is never wrong, only cautious; it never counts as a score or as \"no depth\".\n\n")
                  .Append("What this does not show: real eyes. Test-retest on real players and the one-eye-closed check are measured on the headset (see the submission).\n");
                return sb.ToString();
            }

            static string Rate(int bad, int n) => bad + " of " + n + " (" + (100.0 * bad / Math.Max(1, n)).ToString("0.0#", CultureInfo.InvariantCulture) + " %)";
            static string P(int k, int n) => (100.0 * k / Math.Max(1, n)).ToString("0.0", CultureInfo.InvariantCulture) + " %";
        }

        public static List<Group> DefaultGroups(int n = 1000) => new List<Group>
        {
            new Group { Name = "Steady players", Who = "true threshold 25–700″, few lapses", Expect = Expect.Score, N = n, MinThr = 25, MaxThr = 700 },
            new Group { Name = "Finer than the display", Who = "true threshold 3–10″", Expect = Expect.Floor, N = n / 2, MinThr = 3, MaxThr = 10 },
            new Group { Name = "Distracted players", Who = "25–700″, 15–25 % lapses", Expect = Expect.Score, N = n, MinThr = 25, MaxThr = 700, MinLapse = 0.15, MaxLapse = 0.25 },
            new Group { Name = "Coarse depth only", Who = "true threshold 900–2500″", Expect = Expect.ScoreOrNoDepth, N = n / 2, MinThr = 900, MaxThr = 2500 },
            new Group { Name = "No depth from two eyes", Who = "every answer a guess", Expect = Expect.NoDepth, N = n, GuessOnly = true },
            new Group { Name = "Stutter in 1 of 4 rounds", Who = "steady players; disturbed rounds are guesses", Expect = Expect.Score, N = n, MinThr = 25, MaxThr = 700, DirtyChance = 0.25 },
            new Group { Name = "Broken two-eye view", Who = "both eyes get one image; health check on", Expect = Expect.Uncertain, N = n / 2, MinThr = 25, MaxThr = 700, DirtyChance = 1, GuessOnly = false },
            new Group { Name = "Broken view, no health check", Who = "the same, health check switched off", Expect = Expect.Uncertain, N = n / 2, MinThr = 25, MaxThr = 700, DirtyChance = 1, GateOn = false },
        };

        public static Report Run(double floorArcsec = 15, int seed = 20261110, List<Group> groups = null)
        {
            var report = new Report { Floor = floorArcsec, Seed = seed };
            var master = new Random(seed);
            foreach (var g in groups ?? DefaultGroups())
            {
                var row = new Row { G = g };
                for (int i = 0; i < g.N; i++) RunOne(g, row, floorArcsec, master.Next());
                report.Rows.Add(row);
            }
            return report;
        }

        static void RunOne(Group g, Row row, double floor, int seed)
        {
            var rng = new Random(seed);
            double thr = g.GuessOnly ? 1e7 : DisparityMath.Pow10(Lerp(rng, DisparityMath.Log10(g.MinThr), DisparityMath.Log10(g.MaxThr)));
            double slope = Lerp(rng, g.MinSlope, g.MaxSlope), lapse = Lerp(rng, g.MinLapse, g.MaxLapse);
            var obs = new SimulatedObserver(thr, slope, 0.25, lapse, rng.Next());
            // The answer owed is what the player's eyes can do when paying attention: a distracted
            // player's lapses are not their eyesight. (At 20 % lapses they never reach 79 % at all.)
            double target = new SimulatedObserver(thr, slope, 0.25, Math.Min(lapse, AttentiveLapse)).ArcsecAtProbability(0.794);

            var ladder = new SkillLadder(floor, new[] { SkillLadder.SpotRung(floor) });
            var gate = new TrialGate();
            var lv = new List<double>(); var co = new List<bool>();
            int trials = 0;
            while (!ladder.IsFinished && !(g.GateOn && gate.GaveUp) && trials < 400)
            {
                bool dirty = g.DirtyChance > 0 && rng.NextDouble() < g.DirtyChance;
                // A disturbed round is a guess: the creature wasn't really visible.
                bool correct = dirty || g.GuessOnly ? rng.NextDouble() < 0.25 : obs.Respond(ladder.CurrentArcsec);
                trials++;
                if (!g.GateOn) ladder.Respond(correct);
                else if (gate.Pass(!dirty, "the view wasn't steady")) { lv.Add(ladder.CurrentArcsec); co.Add(correct); ladder.Respond(correct); }
            }
            var v = Verdict.Judge(ladder, g.GateOn ? gate : null, g.GateOn ? lv : null, g.GateOn ? co : null);
            row.Trials.Add(trials);

            switch (v.Result)
            {
                case Verdict.Outcome.Measured: row.Measured++; break;
                case Verdict.Outcome.AtFloor: row.AtFloor++; break;
                case Verdict.Outcome.NoDepth: row.NoDepth++; break;
                default: row.Uncertain++; break;
            }

            bool within158 = false;
            if (v.Result == Verdict.Outcome.Measured)
            {
                double err = Math.Abs(DisparityMath.Log10(v.Arcsec) - DisparityMath.Log10(target));
                row.AbsErrPct.Add((DisparityMath.Pow10(err) - 1) * 100);
                if (DisparityMath.Log10(v.Arcsec) < DisparityMath.Log10(target) - 0.2) row.Flattering++;
                if (err <= 0.1) row.Within126++;
                if (err <= 0.2) { row.Within158++; within158 = true; }
                double half = DisparityMath.Log10(1 + v.PlusMinusPercent / 100);
                if (err <= half) row.Covered++;
            }

            bool right;
            switch (g.Expect)
            {
                case Expect.Score:
                    // Near the display limit, "≤ floor" is the right answer too.
                    right = (v.Result == Verdict.Outcome.Measured && within158) ||
                            (v.Result == Verdict.Outcome.AtFloor && target <= floor * 2);
                    break;
                case Expect.Floor: right = v.Result == Verdict.Outcome.AtFloor; break;
                case Expect.NoDepth: right = v.Result == Verdict.Outcome.NoDepth; break;
                case Expect.ScoreOrNoDepth: right = v.Result == Verdict.Outcome.NoDepth || (v.Result == Verdict.Outcome.Measured && within158); break;
                default: right = v.Result == Verdict.Outcome.Uncertain; break;
            }
            // "Not sure" is cautious, not wrong — except where a definite answer was owed and given wrongly.
            if (right) row.Right++;
            else if (v.Result != Verdict.Outcome.Uncertain || g.Expect == Expect.Uncertain) row.Wrong++;
        }

        static double Lerp(Random r, double a, double b) => a + (b - a) * r.NextDouble();

        static double Median(List<double> v)
        {
            if (v.Count == 0) return double.NaN;
            var a = new List<double>(v); a.Sort();
            return a.Count % 2 == 1 ? a[a.Count / 2] : 0.5 * (a[a.Count / 2 - 1] + a[a.Count / 2]);
        }

        static int MedianInt(List<int> v)
        {
            if (v.Count == 0) return 0;
            var a = new List<int>(v); a.Sort();
            return a[a.Count / 2];
        }
    }
